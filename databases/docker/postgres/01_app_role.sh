#!/usr/bin/env bash
# Инициализация от владельца БД; также допускает явный повторный запуск.
set -euo pipefail
PGPASSWORD="${POSTGRES_PASSWORD:-}" psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
    --set=ON_ERROR_STOP=1 --set=app_password="$POSTGRES_APP_PASSWORD" <<'SQL'
SELECT 'CREATE ROLE study_app LOGIN' WHERE NOT EXISTS (
    SELECT 1 FROM pg_roles WHERE rolname = 'study_app'
) \gexec
ALTER ROLE study_app WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS PASSWORD :'app_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS app_data AUTHORIZATION CURRENT_USER;
REVOKE ALL ON SCHEMA app_data FROM PUBLIC, study_app;
GRANT USAGE ON SCHEMA app_data TO study_app;
GRANT CONNECT, TEMPORARY ON DATABASE :"DBNAME" TO study_app;
ALTER ROLE study_app IN DATABASE :"DBNAME" SET search_path = app_data, public;
CREATE TABLE IF NOT EXISTS app_data.access_demo (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    label text NOT NULL
);
REVOKE ALL ON ALL TABLES IN SCHEMA app_data FROM study_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app_data TO study_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA app_data TO study_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA app_data GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO study_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA app_data GRANT USAGE, SELECT ON SEQUENCES TO study_app;
SQL
